"""Generate data/seed.sql: books, members and 15 months of realistic borrowing history.

    python data/generate_seed.py            # default seed 7
    python data/generate_seed.py --seed 11

Catalogue data is inserted directly. Borrowing history is written as calls to the
stored procedures (sp_issue_book, sp_return_book, sp_pay_fines) in date order, so
the triggers create copy statuses and fines exactly as they would in real use.
The script mirrors the borrowing rules so it only ever writes calls that succeed.
Only the Python standard library is used.
"""
import argparse
import datetime as dt
import random
from pathlib import Path

OUT = Path(__file__).resolve().parent / "seed.sql"
START = dt.date(2025, 7, 1)
END = dt.date(2026, 9, 30)

RULES = {  # member_type: (max_loans, loan_days, fine_per_day, fine_block_limit)
    "student": (3, 14, 5.00, 100.00),
    "staff": (5, 30, 2.00, 200.00),
}

CATEGORIES = {
    "Computer Science": ["Data Structures", "Algorithms", "Operating Systems", "Computer Networks", "Databases",
                         "Compilers", "Machine Learning", "Software Engineering", "Cloud Computing", "Cyber Security",
                         "Java Programming", "Python Programming", "Web Development", "Discrete Mathematics"],
    "Fiction": ["The Monsoon House", "Letters from Kochi", "A River in Pune", "The Last Tram", "Midnight Chai",
                "Salt and Saffron", "The Quiet Platform", "Paper Boats", "City of Lanterns", "The Ninth Monsoon"],
    "Exam Prep": ["GATE Computer Science", "Quantitative Aptitude", "Logical Reasoning", "Verbal Ability",
                  "Placement Interview Guide", "Coding Interview Patterns", "GRE Word List", "CAT Mock Papers"],
    "Business": ["Startup Basics", "Marketing Made Simple", "Personal Finance", "Leadership Notes",
                 "Product Thinking", "Negotiation"],
    "Self-help": ["Deep Focus", "Small Habits", "Thinking Clearly", "The Calm Mind", "Learning How to Learn"],
}
SUBTITLES = ["", ": A Practical Guide", ": Concepts and Practice", " Explained", ": Second Edition", " for Beginners"]
PUBLISHERS = ["Deccan Press", "Sahyadri Books", "Lotus Publishing", "Indus Academic", "Monsoon House Books",
              "Tech Shelf India"]
FIRST = ["Aarav", "Ananya", "Rohan", "Isha", "Kabir", "Meera", "Vikram", "Diya", "Arjun", "Sneha", "Nikhil", "Pooja",
         "Rahul", "Kavya", "Siddharth", "Riya", "Aditya", "Neha", "Omkar", "Tanvi", "Harsh", "Shruti", "Yash", "Aditi"]
LAST = ["Patil", "Sharma", "Iyer", "Reddy", "Kulkarni", "Deshmukh", "Nair", "Joshi", "Gupta", "Rao", "Shinde",
        "Menon", "Pawar", "Bhat", "Kapoor", "Chavan"]
COUNTRIES = ["India", "India", "India", "UK", "USA", "Canada"]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main(seed):
    rnd = random.Random(seed)
    lines = ["-- Generated by data/generate_seed.py - do not edit by hand", "USE library;", ""]

    # ---- rules
    lines.append("INSERT INTO membership_rules (member_type, max_loans, loan_days, fine_per_day, fine_block_limit) VALUES")
    lines.append(",\n".join(f"({q(t)}, {a}, {b}, {c:.2f}, {d:.2f})" for t, (a, b, c, d) in RULES.items()) + ";")

    # ---- publishers & authors
    lines.append("INSERT INTO publishers (publisher_id, name) VALUES")
    lines.append(",\n".join(f"({i}, {q(n)})" for i, n in enumerate(PUBLISHERS, 1)) + ";")
    authors = []
    seen = set()
    while len(authors) < 60:
        name = f"{rnd.choice(FIRST)} {rnd.choice(LAST)}"
        if name not in seen:
            seen.add(name)
            authors.append((len(authors) + 1, name, rnd.choice(COUNTRIES)))
    lines.append("INSERT INTO authors (author_id, full_name, country) VALUES")
    lines.append(",\n".join(f"({i}, {q(n)}, {q(c)})" for i, n, c in authors) + ";")

    # ---- books, book_authors, copies
    books, book_authors, copies = [], [], []
    popularity = {}
    copy_id = 1
    for cat, titles in CATEGORIES.items():
        for title in titles:
            book_id = len(books) + 1
            full = title + (rnd.choice(SUBTITLES) if cat in ("Computer Science", "Exam Prep") else "")
            isbn = "978" + "".join(str(rnd.randint(0, 9)) for _ in range(10))
            books.append((book_id, isbn, full, cat, rnd.randint(1, len(PUBLISHERS)), rnd.randint(1998, 2025)))
            for a in rnd.sample(authors, rnd.choices([1, 2, 3], [0.65, 0.28, 0.07])[0]):
                book_authors.append((book_id, a[0]))
            n_copies = {"Computer Science": 4, "Exam Prep": 5}.get(cat, 2) + rnd.randint(-1, 1)
            for _ in range(max(1, n_copies)):
                copies.append((copy_id, book_id, f"{cat[:2].upper()}-{rnd.randint(1, 40):02d}",
                               (START - dt.timedelta(days=rnd.randint(30, 1500))).isoformat()))
                copy_id += 1
            popularity[book_id] = {"Computer Science": 3.0, "Exam Prep": 4.0, "Fiction": 1.4}.get(cat, 1.0) * rnd.uniform(0.3, 1.8)

    lines.append("INSERT INTO books (book_id, isbn, title, category, publisher_id, published_year) VALUES")
    lines.append(",\n".join(f"({b[0]}, {q(b[1])}, {q(b[2])}, {q(b[3])}, {b[4]}, {b[5]})" for b in books) + ";")
    lines.append("INSERT INTO book_authors (book_id, author_id) VALUES")
    lines.append(",\n".join(f"({b}, {a})" for b, a in book_authors) + ";")
    lines.append("INSERT INTO copies (copy_id, book_id, shelf, acquired_on) VALUES")
    lines.append(",\n".join(f"({c[0]}, {c[1]}, {q(c[2])}, {q(c[3])})" for c in copies) + ";")

    # ---- members
    members = []
    for mid in range(1, 301):
        first, last = rnd.choice(FIRST), rnd.choice(LAST)
        mtype = "staff" if rnd.random() < 0.12 else "student"
        active = 0 if rnd.random() < 0.05 else 1
        members.append({"id": mid, "name": f"{first} {last}", "email": f"{first.lower()}.{last.lower()}{mid}@college.example",
                        "type": mtype, "joined": (START - dt.timedelta(days=rnd.randint(0, 700))).isoformat(),
                        "active": active, "weight": rnd.paretovariate(1.8)})
    lines.append("INSERT INTO members (member_id, full_name, email, member_type, joined_on, is_active) VALUES")
    lines.append(",\n".join(f"({m['id']}, {q(m['name'])}, {q(m['email'])}, {q(m['type'])}, {q(m['joined'])}, {m['active']})"
                            for m in members) + ";")

    # ---- borrowing history (simulated with the same rules as the procedures)
    lines += ["", "-- Borrowing history, replayed through the stored procedures"]
    copy_status = {c[0]: "available" for c in copies}
    copies_by_book = {}
    for c in copies:
        copies_by_book.setdefault(c[1], []).append(c[0])
    open_loans = {}          # copy_id -> (member_id, due_date, planned_return_date)
    open_count = {m["id"]: 0 for m in members}
    unpaid = {m["id"]: 0.0 for m in members}
    pay_on = {}              # member_id -> date they will pay
    active_members = [m for m in members if m["active"]]
    weights = [m["weight"] for m in active_members]
    book_ids = list(popularity)
    book_w = [popularity[b] for b in book_ids]
    calls = {"issue": 0, "return": 0, "pay": 0}

    day = START
    while day <= END:
        # returns first
        for cid, (mid, due, ret) in sorted(open_loans.items()):
            if ret == day:
                lines.append(f"CALL sp_return_book({cid}, {q(day.isoformat())});")
                calls["return"] += 1
                late = (day - due).days
                if late > 0:
                    rate = RULES[members[mid - 1]["type"]][2]
                    unpaid[mid] += late * rate
                    if mid not in pay_on and rnd.random() < 0.7:
                        pay_on[mid] = day + dt.timedelta(days=rnd.randint(1, 30))
                copy_status[cid] = "available"
                open_count[mid] -= 1
                del open_loans[cid]
        # payments
        for mid, when in list(pay_on.items()):
            if when == day:
                lines.append(f"CALL sp_pay_fines({mid}, {q(day.isoformat())});")
                calls["pay"] += 1
                unpaid[mid] = 0.0
                del pay_on[mid]
        # new loans: busier on weekdays and around exam months
        base = 9 if day.weekday() < 5 else 3
        if day.month in (11, 12, 4, 5):
            base = int(base * 1.5)
        if day.month in (6,):
            base = int(base * 0.5)
        for _ in range(rnd.randint(int(base * 0.6), int(base * 1.4))):
            m = rnd.choices(active_members, weights)[0]
            mtype = m["type"]
            max_loans, loan_days, _rate, block = RULES[mtype]
            if open_count[m["id"]] >= max_loans or unpaid[m["id"]] >= block:
                continue
            book = rnd.choices(book_ids, book_w)[0]
            free = [c for c in copies_by_book[book] if copy_status[c] == "available"]
            if not free:
                continue
            cid = min(free)
            due = day + dt.timedelta(days=loan_days)
            r = rnd.random()
            if r < 0.70:
                ret = day + dt.timedelta(days=rnd.randint(2, loan_days))
            elif r < 0.95:
                ret = due + dt.timedelta(days=rnd.randint(1, 20))
            else:
                ret = due + dt.timedelta(days=rnd.randint(21, 60))
            if ret > END:
                ret = None  # still out at the end of the data
            lines.append(f"CALL sp_issue_book({m['id']}, {book}, {q(day.isoformat())});")
            calls["issue"] += 1
            copy_status[cid] = "on_loan"
            open_count[m["id"]] += 1
            open_loans[cid] = (m["id"], due, ret)
        day += dt.timedelta(days=1)

    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"books {len(books)}, copies {len(copies)}, members {len(members)}, "
          f"issues {calls['issue']}, returns {calls['return']}, payments {calls['pay']}, still out {len(open_loans)}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, default=7)
    main(ap.parse_args().seed)
